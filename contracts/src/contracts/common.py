"""Shared building blocks for every contract.

Conventions (frozen in contracts v0.2, see docs/decisions):
- JSON field names are snake_case.
- IDs are UUIDs, generated by the server in application code (time-ordered UUIDv7 when available).
- Timestamps are ISO 8601 in UTC. Dates are YYYY-MM-DD. Currency is an ISO 4217 code.
- Money and quantities are Decimal in Python and *strings* in JSON ("420000.00"), never floats.
- Unknown optional values are null, never missing keys.
- Requests reject unknown fields (extra="forbid"); responses ignore them (tolerant reader).
"""
from __future__ import annotations

import uuid
from decimal import Decimal
from typing import Annotated

from pydantic import BaseModel, BeforeValidator, ConfigDict, Field, StringConstraints


def new_id() -> uuid.UUID:
    """Time-ordered UUID (v7) when available, otherwise random v4.

    Newer Python versions ship uuid.uuid7; otherwise the optional `uuid_utils` package is used.
    Verify which one your Python provides. Clients never choose IDs; servers do.
    """
    gen = getattr(uuid, "uuid7", None)
    if gen is not None:
        return gen()
    try:
        import uuid_utils  # type: ignore[import-not-found]

        return uuid.UUID(str(uuid_utils.uuid7()))
    except (ImportError, AttributeError):
        return uuid.uuid4()


def _reject_float(value: object) -> object:
    if isinstance(value, float):
        raise ValueError("send money and quantities as strings (or integers), never floats")
    return value


Money = Annotated[Decimal, BeforeValidator(_reject_float), Field(max_digits=14, decimal_places=2)]
Quantity = Annotated[Decimal, BeforeValidator(_reject_float), Field(max_digits=12, decimal_places=3)]
Percent = Annotated[Decimal, BeforeValidator(_reject_float), Field(max_digits=7, decimal_places=2)]
Currency = Annotated[str, StringConstraints(pattern=r"^[A-Z]{3}$")]


class RequestModel(BaseModel):
    """Base for anything a client sends: unknown fields are an error."""

    model_config = ConfigDict(extra="forbid")


class ResponseModel(BaseModel):
    """Base for anything a service returns: unknown fields are ignored so services can add fields safely."""

    model_config = ConfigDict(extra="ignore")
